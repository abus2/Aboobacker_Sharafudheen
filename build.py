"""Rebuild apps.html (gallery + panels), apps.js and downloads/*.html from apps-src/.
Usage:  python build.py
To add an app: add apps-src/<id>.html + apps-src/<id>.js and one entry in apps-src/apps.json, then run this."""
import json, re, os
os.chdir(os.path.dirname(os.path.abspath(__file__)))
rd = lambda p: open(p, encoding='utf-8').read()
meta = json.load(open('apps-src/apps.json', encoding='utf-8'))
helpers = rd('apps-src/_helpers.js')

# ---- apps.html
cards, panels = [], []
for n, a in enumerate(meta, 1):
    cards.append(f'''<article class="hub-card glass-card"><div class="hub-top"><i class="hub-ico" aria-hidden="true">{a['icon']}</i><span class="hub-num">APP {n:02d}</span></div>
  <h3>{a['title']}</h3><p>{a['desc']}</p>
  <div class="hub-actions"><a class="hub-btn primary hub-try" href="#{a['id']}" data-app="{a['id']}">Try now →</a><a class="hub-btn ghost" href="downloads/{a['file']}.html" download>⇩ Download</a></div></article>''')
    p = rd(f"apps-src/{a['id']}.html").replace('class="app-panel"', 'class="app-panel"', 1)
    panels.append(p.strip())
block = ('<!--APPS:START-->\n<div class="app-hub" id="appHub">\n' + '\n'.join(cards) + '\n</div>\n'
  '<div class="app-bar" id="appBar" hidden><button type="button" id="appBack">← All apps</button><b></b></div>\n\n'
  + '\n\n'.join(panels) + '\n    <!--APPS:END-->')
h = rd('apps.html')
h = re.sub(r'<!--APPS:START-->.*<!--APPS:END-->', lambda m: block, h, flags=re.S)
n = len(meta)
h = re.sub(r'<div class="page-stats">.*?</div></div>\n', f'<div class="page-stats"><div><b>{n}</b><span>WORKING APPS</span></div><div><b>0</b><span>DATA UPLOADED</span></div><div><b>1–9</b><span>KEYS OPEN APPS</span></div></div>\n', h, count=1, flags=re.S)
h = re.sub(r'<p>(?:Eight|\d+) (?:small )?apps.*?</p>', f'<p>{n} apps built with HTML, CSS and JavaScript: a Tally-style accounts book, invoice, stock register and calculators. Pick any app and press <b>Try now</b> to use it here, or <b>Download</b> to get a single file that works offline. Everything runs in your browser and nothing is uploaded.</p>', h, count=1, flags=re.S)
h = h.replace('GST, EMI, SIP growth, budget tracker and profit calculator.', 'GST, EMI, SIP, budget, FD/RD, break-even, interest, BMI and more. Try now or download.')
if 'apps-hub.css' not in h:
    h = h.replace('<link rel="stylesheet" href="clean.css" />', '<link rel="stylesheet" href="clean.css" />\n  <link rel="stylesheet" href="apps-hub.css" />')
for tag in ('downloads-data.js', 'download-buttons.js'):
    if tag not in h:
        h = h.replace('<script src="apps.js"></script>', f'<script src="{tag}"></script>\n  <script src="apps.js"></script>')
open('apps.html', 'w', encoding='utf-8').write(h)

# ---- apps.js
body = '\n\n'.join(f"// ---------- {i}. {a['title'].replace('&amp;','&')} ----------\n" + rd(f"apps-src/{a['id']}.js").strip() for i, a in enumerate(meta, 1))
open('apps.js', 'w', encoding='utf-8').write(
 '// apps.html: app gallery (Try now / Download) + working calculators. GENERATED by build.py from apps-src/.\n(function(){\n'
 + helpers + '\n' + rd('apps-src/_hub.js') + '\n\n' + body + '\n})();\n')

# ---- standalone downloads
pc = rd('pages.css')
css = pc[pc.index('/* ============ APPS PAGE'):pc.index('/* ============ HOME PAGE')]
css = '\n'.join(l for l in css.split('\n') if not re.match(r'\.app-tabs?[{:.]|\.app-tab[ {:.]|\.app-panel\{|@media\(max-width:900px\)', l) and 'app-tab' not in l)
css = rd('apps-hub.css') + ':root{--p-blue:#3a6bff;--p-blue2:#7da0ff;--p-line:rgba(125,160,255,.2);--p-ok:#38d39f;--p-bad:#ff6b81;--font:"DM Sans",system-ui,Arial,sans-serif;--display:"Space Grotesk","DM Sans",system-ui,Arial,sans-serif}' \
 '*{box-sizing:border-box;margin:0;padding:0}body{background:#050d24;color:#edf2ff;font-family:var(--font);line-height:1.6;padding:24px}' \
 'button,input,select{font-family:inherit}.sa{max-width:1000px;margin:0 auto}.sa-head{display:flex;align-items:center;gap:12px;margin-bottom:22px;font-size:11px;letter-spacing:1.6px;color:#8fa2d0;font-weight:700}' \
 '.sa-head i{font-style:normal;width:30px;height:30px;border-radius:9px;background:#3a6bff;color:#fff;display:grid;place-items:center}' \
 '.glass-card{background:#0b1a4a;border:1px solid var(--p-line)}.app-card.result{display:grid;gap:18px;align-content:start}.app-panel{display:block}' \
 '.button{display:inline-flex;align-items:center;gap:8px;height:46px;padding:0 22px;border-radius:12px;background:#3a6bff;color:#fff;border:0;font-weight:600;cursor:pointer}' \
 '.toast{position:fixed;left:50%;bottom:24px;transform:translateX(-50%);background:#0a1636;border:1px solid var(--p-line);padding:10px 18px;border-radius:12px;font-size:13px;opacity:0;pointer-events:none;transition:opacity .2s}.toast.show{opacity:1}' \
 '@media(max-width:900px){.app-grid{grid-template-columns:1fr}}' + css
shim = '''window.PF2={$:(s,r)=>(r||document).querySelector(s),$$:(s,r)=>[...(r||document).querySelectorAll(s)],reduce:false,
 toast:m=>{const t=document.getElementById('toast');t.textContent=m;t.classList.add('show');clearTimeout(window.__t);window.__t=setTimeout(()=>t.classList.remove('show'),2200);}};
window.PF_RENDER={esc:s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]))};'''
os.makedirs('downloads', exist_ok=True)
for i, a in enumerate(meta, 1):
    panel = rd(f"apps-src/{a['id']}.html").replace('class="app-panel"', 'class="app-panel active"', 1)
    title = a['title'].replace('&amp;', '&')
    page = f'''<!DOCTYPE html>
<html lang="en"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title} | Aboobacker Sharfudheen</title>
<style>{css}</style></head>
<body><main class="sa"><div class="sa-head"><i>{a['icon']}</i>{title.upper()} · BY ABOOBACKER SHARFUDHEEN · WORKS OFFLINE</div>
{panel}</main><div class="toast" id="toast" role="status" aria-live="polite"></div>
<script>{shim}
(function(){{
{helpers}
{rd(f"apps-src/{a['id']}.js")}
}})();</script></body></html>
'''
    open(f"downloads/{a['file']}.html", 'w', encoding='utf-8').write(page)

# ---- standalone offline copy of the Tally Prime page (tally.html)
th = rd('tally.html')
blk = re.search(r'<!--TALLY:START-->(.*?)<!--TALLY:END-->', th, re.S).group(1)
blk = re.sub(r'<a class="mini-btn" href="downloads/tally-prime-accounts.html"[^>]*>.*?</a>', '', blk, flags=re.S)
tcss = css + rd('tally-page.css')
tpage = f'''<!DOCTYPE html>
<html lang="en"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Tally Prime Accounts | Aboobacker Sharfudheen</title>
<style>{tcss}.sa{{max-width:1200px}}</style></head>
<body><main class="sa"><div class="sa-head"><i>₹</i>TALLY PRIME ACCOUNTS · BY ABOOBACKER SHARFUDHEEN · WORKS OFFLINE</div>
{blk}</main><div class="toast" id="toast" role="status" aria-live="polite"></div>
<script>{shim}
{rd('tally-page.js')}</script></body></html>
'''
open('downloads/tally-prime-accounts.html', 'w', encoding='utf-8').write(tpage)

# ---- downloads-data.js: every download file embedded so the Download buttons work everywhere
# (the plain <a download> attribute is ignored by browsers when a page is opened from a file:// path)
files = {a['file']: rd(f"downloads/{a['file']}.html") for a in meta}
files['tally-prime-accounts'] = tpage
open('downloads-data.js', 'w', encoding='utf-8').write(
 '// GENERATED by build.py - the standalone files behind every Download button.\nwindow.PF_DOWNLOADS=' + json.dumps(files, ensure_ascii=False).replace('</', '<\\/') + ';\n')
print('built', len(meta), 'apps + tally-prime-accounts')
